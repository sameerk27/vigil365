<#
.SYNOPSIS
  Rebuilds the licence posture entitlement map from Microsoft's licensing CSV.

.DESCRIPTION
  Licence posture (docs/LICENSE_POSTURE_PLAN.md) never types a SKU or service-plan
  identifier from memory. This script reads Microsoft's "Product names and service
  plan identifiers for licensing" CSV and writes
  src/M365SecurityDashboard.Api/Data/Posture/entitlements.json:

    - skus:          the SKUs posture can recommend, each with its service plans
    - servicePlans:  every service plan those SKUs include (name, id, friendly name)
    - productNames:  String_Id -> product name for every SKU in the CSV, so the UI
                     can name whatever licences a tenant owns

  It reads only. Re-run it when Microsoft updates the CSV and commit the result.

.PARAMETER CsvPath
  A copy of the CSV already on disk. Without it, the CSV is downloaded from Microsoft.

.PARAMETER SourceLastModified
  The CSV's Last-Modified date (yyyy-MM-dd) when -CsvPath is used. Downloads read it
  from the response.

.PARAMETER Skus
  String_Id values to include in "skus". Default: Business Premium, E3, E5 and the two
  add-ons posture suggests (Entra ID P2, Defender for Office 365 Plan 2).

.EXAMPLE
  pwsh -File scripts/update-entitlements.ps1
.EXAMPLE
  pwsh -File scripts/update-entitlements.ps1 -CsvPath .\licensing.csv -SourceLastModified 2026-08-19
#>
[CmdletBinding()]
param(
  [string]$CsvPath,
  [string]$SourceLastModified,
  [string[]]$Skus = @('SPB', 'SPE_E3', 'SPE_E5', 'AAD_PREMIUM_P2', 'THREAT_INTELLIGENCE'),
  [string]$OutFile = (Join-Path (Split-Path -Parent $PSScriptRoot) 'src/M365SecurityDashboard.Api/Data/Posture/entitlements.json')
)

$ErrorActionPreference = 'Stop'
$sourceUrl = 'https://download.microsoft.com/download/e/3/e/e3e9faf2-f28b-490a-9ada-c6089a1fc5b0/Product%20names%20and%20service%20plan%20identifiers%20for%20licensing.csv'

if (-not $CsvPath) {
  $CsvPath = Join-Path ([IO.Path]::GetTempPath()) 'vigil365-licensing.csv'
  $response = Invoke-WebRequest -Uri $sourceUrl -OutFile $CsvPath -PassThru -TimeoutSec 120
  $SourceLastModified = ([DateTimeOffset]::Parse([string]$response.Headers['Last-Modified'])).ToString('yyyy-MM-dd')
}
if (-not $SourceLastModified) { throw 'Pass -SourceLastModified (yyyy-MM-dd) with -CsvPath, so the data file records which version of the CSV it came from.' }

$rows = Import-Csv -LiteralPath $CsvPath
$expected = 'Product_Display_Name', 'String_Id', 'GUID', 'Service_Plan_Name', 'Service_Plan_Id', 'Service_Plans_Included_Friendly_Names'
$missing = $expected | Where-Object { $_ -notin $rows[0].PSObject.Properties.Name }
if ($missing) { throw "The CSV no longer has the expected columns: $($missing -join ', '). Check Microsoft's format before regenerating." }

$skuEntries = foreach ($id in $Skus) {
  $skuRows = @($rows | Where-Object { $_.String_Id -eq $id })
  if ($skuRows.Count -eq 0) { throw "SKU '$id' is not in the CSV." }
  [ordered]@{
    stringId     = $id
    guid         = $skuRows[0].GUID
    name         = $skuRows[0].Product_Display_Name.Trim()
    servicePlans = @($skuRows.Service_Plan_Name | Sort-Object -Unique)
  }
}

$planRows = $rows | Where-Object { $_.String_Id -in $Skus }
$servicePlans = $planRows | Group-Object Service_Plan_Name | Sort-Object Name | ForEach-Object {
  [ordered]@{ name = $_.Name; id = $_.Group[0].Service_Plan_Id; friendlyName = $_.Group[0].Service_Plans_Included_Friendly_Names.Trim() }
}

$productNames = [ordered]@{}
$rows | Group-Object String_Id | Sort-Object Name | ForEach-Object { $productNames[$_.Name] = $_.Group[0].Product_Display_Name.Trim() }

$doc = [ordered]@{
  '$comment'   = "Generated by scripts/update-entitlements.ps1 from Microsoft's 'Product names and service plan identifiers for licensing' CSV. Do not edit by hand; re-run the script."
  source       = [ordered]@{ url = $sourceUrl; retrieved = (Get-Date -Format 'yyyy-MM-dd'); lastModified = $SourceLastModified }
  skus         = @($skuEntries)
  servicePlans = @($servicePlans)
  productNames = $productNames
}

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutFile) | Out-Null
$doc | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $OutFile -Encoding utf8
Write-Host "Wrote ${OutFile}: $($skuEntries.Count) SKUs, $(@($servicePlans).Count) service plans, $($productNames.Count) product names."
